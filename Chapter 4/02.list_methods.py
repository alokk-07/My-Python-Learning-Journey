l1 = [1,8,7,2,21,15]

# list methods 

l1.sort()    # ascending  
print(l1)

l1.reverse()  
print(l1)

l1.append(8)  # add value at the end of the list 
print(l1)

l1.insert(3,11)  #insert 8 such that  its index in the list is 3 
print(l1)

l1.pop(2)   # it remove the value from the index 2   #i.e.7 
print(l1)
print(l1.pop(3)) # it will write the value of index 3   #i.e.7

l1.remove(21)  # remove a particular value 
print(l1)







