friends = [ "Apple", "Orange", 5, 345.6, False ]

print(friends [0])   # output: Apple
friends[0] = "Grapes"    # unlike strings , lists are mutable

# now the new list become : ["Orange", "Orange", 5, 345.6, False]
print(friends[0])       # output: Grapes

print(friends[4])
print(friends[1:4])    #  list string 

