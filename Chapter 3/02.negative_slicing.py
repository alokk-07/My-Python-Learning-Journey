name = "Alok"

print(name [0:3])   #start from index 0 and go till end of string 3

# given below both codes are same 
print(name[-3:-1])   #start from index -3 and go till end of string -1
print(name[1:3])    #start from index 1 and go till end of string 3

# given below both codes are same 
print(name[:3])    #start from index 0 and go till end of string 3
print(name[0:3])    #start from index 0 and go till end of string 3

# given below both codes are same 
print(name[1:])    #start from index 1 and go till end of string
print(name[1:4])  #start from index 1 and go till end of string 4 but since string has only 4 character so it will print till end of string