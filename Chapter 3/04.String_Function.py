name="alok"



print(len(name))  # length of string
print(name.endswith("k"))  # check if string ends with "k"
print(name.startswith("a"))  # check if string starts with "a"
print(name.capitalize())  # capitalize the first letter of the string
print(name.upper())  # convert string to uppercase
print(name.lower())  # convert string to lowercase
print(name.find("l"))  # find the index of the first occurrence of "l"
print(name.replace("a", "1"))  # replace "a" with "1" in the string
print(name.count("o"))  # count the occurrences of "o" in the string
print(name.isnumeric())  # check if the string is numeric
print(name.isalpha())  # check if the string contains only alphabetic characters
print(name.isalnum())  # check if the string is alphanumeric
print(name.split("o"))  # split the string at "o"
print(name.strip())  # remove leading and trailing whitespace from the string
print(name.index("k"))  # find the index of the first occurrence of "k"
print(name.islower())  # check if all characters in the string are lowercase
print(name.isupper())  # check if all characters in the string are uppercase